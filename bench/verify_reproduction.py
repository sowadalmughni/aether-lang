#!/usr/bin/env python3
"""
bench/verify_reproduction.py

Diff freshly produced benchmark JSONs against the committed reference set in
bench/results/. Drives `reproduce.sh`'s acceptance check.

Comparison strategy (declared in bench/verify_tolerance.toml):

  - exact_required: fields that must match the reference exactly (structural
    invariants like system/provider/configs and deterministic numerics like
    tokens, EM/F1, cache_hit_rate).
  - numeric_tolerant: fields whose .mean must lie within reference.ci95 widened
    by the listed fractional tolerance. Used for wall-clock latencies, which
    are hardware-bound even in mock mode.
  - ignore: glob patterns excluded from comparison (timestamps, raw trial
    arrays, hardware metadata).
  - requires_real_api: JSON files the mock reproducer cannot regenerate.
    Marked "n/a (requires OPENAI_API_KEY)" in the report; not a failure.

Exit codes:
  0 -- all comparable files matched within tolerance
  1 -- structural mismatch (exact_required field differs) or missing produced file
  2 -- numeric drift outside tolerance (--strict-numeric promotes this to fail)

Stdlib-only (Python 3.11+: tomllib in stdlib).
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import sys
import tomllib
from pathlib import Path
from typing import Any


REPORT_HEADER = """# Reproduction Diff Report

Generated by `bench/verify_reproduction.py`.

| File | Field | Reference | Produced | Tolerance | Verdict |
| --- | --- | --- | --- | --- | --- |
"""


class Tolerance:
    def __init__(self, cfg_path: Path) -> None:
        with cfg_path.open("rb") as f:
            cfg = tomllib.load(f)
        self.exact_required: set[str] = set(cfg.get("exact_required", []))
        self.numeric_tolerant: dict[str, float] = dict(cfg.get("numeric_tolerant", {}))
        self.ignore_patterns: list[str] = list(cfg.get("ignore", []))
        self.requires_real_api: set[str] = set(cfg.get("requires_real_api", []))
        self.skip: set[str] = set(cfg.get("skip", []))

    def is_ignored(self, dotted_path: str) -> bool:
        # leaf field name shortcut: a single trailing component might appear
        # in the ignore list verbatim (e.g. "measured_at", "hardware")
        last = dotted_path.split(".")[-1]
        for pat in self.ignore_patterns:
            if pat == last or pat == dotted_path:
                return True
            if fnmatch.fnmatchcase(dotted_path, pat):
                return True
        return False

    def is_exact_required(self, dotted_path: str) -> bool:
        last = dotted_path.split(".")[-1]
        return last in self.exact_required

    def numeric_tolerance_for(self, dotted_path: str) -> float | None:
        last = dotted_path.split(".")[-1]
        return self.numeric_tolerant.get(last)


class Verdict:
    OK = "ok"
    DRIFT = "drift"          # numeric drift, soft fail
    MISMATCH = "mismatch"    # structural mismatch, hard fail
    SKIP_REAL_API = "n/a (requires OPENAI_API_KEY)"
    SKIP = "skipped"
    MISSING = "missing produced file"


def fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.6g}"
    if isinstance(v, (list, dict)):
        return f"<{type(v).__name__}>"
    return str(v)


def _find_unique_id_keys(items: list) -> tuple[str, ...] | None:
    """
    Greedily build a tuple of dict keys whose values uniquely identify each
    list element. Used to pair list-of-dict elements between ref and produced
    so that order-of-elements isn't load-bearing.

    Returns None if no such key tuple exists from the candidate set.
    """
    candidates = ("id", "config", "dataset", "name", "bucket")
    present = [c for c in candidates if all(isinstance(r, dict) and c in r for r in items)]
    selected: list[str] = []
    for c in present:
        selected.append(c)
        vals = [tuple(r[k] for k in selected) for r in items]
        # Use repr so unhashable values (lists/dicts) don't crash set()
        if len(set(repr(v) for v in vals)) == len(vals):
            return tuple(selected)
    return None


def is_mean_ci95_block(node: Any) -> bool:
    return (
        isinstance(node, dict)
        and "mean" in node
        and "ci95" in node
        and isinstance(node["ci95"], list)
        and len(node["ci95"]) == 2
    )


def compare_node(
    ref: Any,
    prod: Any,
    path: str,
    tol: Tolerance,
    rows: list[tuple[str, str, str, str, str, str]],
    file_label: str,
) -> tuple[bool, bool]:
    """
    Recursively compare ref vs prod.

    Returns (any_mismatch, any_drift) booleans.
    Appends one row per leaf comparison or per fail-of-interest to `rows`.
    """
    any_mismatch = False
    any_drift = False

    if tol.is_ignored(path):
        return False, False

    # Numeric-tolerant fields: ref is expected to be a {mean, ci95, ...} block.
    num_tol = tol.numeric_tolerance_for(path)
    if num_tol is not None and is_mean_ci95_block(ref):
        if not is_mean_ci95_block(prod):
            rows.append((file_label, path, fmt(ref.get("mean")), fmt(prod), f"+/-{num_tol*100:.0f}%", Verdict.MISMATCH))
            return True, False
        ref_lo, ref_hi = ref["ci95"]
        # Widen the reference CI by the fractional tolerance (centred on mean).
        center = float(ref["mean"]) if ref["mean"] is not None else 0.0
        widen = abs(center) * num_tol
        lo = ref_lo - widen
        hi = ref_hi + widen
        prod_mean = prod["mean"]
        verdict = Verdict.OK if (lo <= prod_mean <= hi) else Verdict.DRIFT
        rows.append((file_label, path, fmt(ref["mean"]), fmt(prod_mean), f"[{fmt(lo)}, {fmt(hi)}]", verdict))
        if verdict == Verdict.DRIFT:
            any_drift = True
        return False, any_drift

    # Dict: recurse.
    if isinstance(ref, dict) and isinstance(prod, dict):
        for k in ref.keys():
            child_path = f"{path}.{k}" if path else k
            if k not in prod:
                if tol.is_ignored(child_path):
                    continue
                rows.append((file_label, child_path, fmt(ref[k]), "<missing>", "exact", Verdict.MISMATCH))
                any_mismatch = True
                continue
            m, d = compare_node(ref[k], prod[k], child_path, tol, rows, file_label)
            any_mismatch = any_mismatch or m
            any_drift = any_drift or d
        # Extra keys in prod (not in ref) are not flagged; the reference is authoritative.
        return any_mismatch, any_drift

    # List: try to pair-up by id-like key tuple, else compare element-wise.
    if isinstance(ref, list) and isinstance(prod, list):
        id_keys = _find_unique_id_keys(ref) if ref and isinstance(ref[0], dict) else None
        if id_keys:
            def _id_of(r: dict) -> tuple:
                return tuple(r.get(k) for k in id_keys)
            prod_by_id = {_id_of(r): r for r in prod if isinstance(r, dict)}
            for r in ref:
                rid = _id_of(r)
                child_path = f"{path}[{','.join(f'{k}={v}' for k, v in zip(id_keys, rid))}]"
                pr = prod_by_id.get(rid)
                if pr is None:
                    rows.append((file_label, child_path, fmt(r), "<missing>", "exact", Verdict.MISMATCH))
                    any_mismatch = True
                    continue
                m, d = compare_node(r, pr, child_path, tol, rows, file_label)
                any_mismatch = any_mismatch or m
                any_drift = any_drift or d
            return any_mismatch, any_drift

        # Element-wise compare (best for parallel arrays of dataset/config names).
        if len(ref) != len(prod):
            if tol.is_exact_required(path):
                rows.append((file_label, path, f"len={len(ref)}", f"len={len(prod)}", "exact", Verdict.MISMATCH))
                return True, False
            # not exact_required: warn-only via drift
            rows.append((file_label, path, f"len={len(ref)}", f"len={len(prod)}", "exact", Verdict.DRIFT))
            return False, True
        for i, (r, p) in enumerate(zip(ref, prod)):
            m, d = compare_node(r, p, f"{path}[{i}]", tol, rows, file_label)
            any_mismatch = any_mismatch or m
            any_drift = any_drift or d
        return any_mismatch, any_drift

    # Scalars: exact compare, but only flag if the leaf is in exact_required
    # (otherwise the field is "informational" and a difference is reported as drift).
    if ref == prod:
        return False, False

    if tol.is_exact_required(path):
        rows.append((file_label, path, fmt(ref), fmt(prod), "exact", Verdict.MISMATCH))
        return True, False
    # type-mismatched scalar where the leaf isn't tracked: report as drift.
    rows.append((file_label, path, fmt(ref), fmt(prod), "informational", Verdict.DRIFT))
    return False, True


def render_report(rows: list[tuple[str, ...]]) -> str:
    out = [REPORT_HEADER]
    for r in rows:
        out.append("| " + " | ".join(r) + " |")
    return "\n".join(out) + "\n"


def main() -> int:
    here = Path(__file__).resolve().parent
    repo_root = here.parent

    ap = argparse.ArgumentParser(description="Diff produced benchmark JSONs against committed reference.")
    ap.add_argument("--reference", default=str(repo_root / "bench" / "results"))
    ap.add_argument("--produced", default=str(repo_root / "bench" / "results" / "repro"))
    ap.add_argument("--tolerance", default=str(here / "verify_tolerance.toml"))
    ap.add_argument("--report", default=str(repo_root / "bench" / "results" / "repro" / "DIFF_REPORT.md"))
    ap.add_argument("--strict-numeric", action="store_true",
                    help="Promote numeric drift (Verdict.DRIFT) to a hard failure (exit 2).")
    args = ap.parse_args()

    tol = Tolerance(Path(args.tolerance))
    ref_dir = Path(args.reference)
    prod_dir = Path(args.produced)
    rows: list[tuple[str, ...]] = []

    any_mismatch = False
    any_drift = False

    # Iterate over every committed reference JSON.
    ref_files = sorted(p for p in ref_dir.iterdir() if p.suffix == ".json")
    if not ref_files:
        print(f"No JSON files found in {ref_dir}", file=sys.stderr)
        return 1

    summary: list[str] = []
    for ref_path in ref_files:
        name = ref_path.name
        if name in tol.skip:
            summary.append(f"{name}: skipped (legacy)")
            continue
        if name in tol.requires_real_api:
            summary.append(f"{name}: {Verdict.SKIP_REAL_API}")
            rows.append((name, "(file)", "real-API JSON", "n/a", "n/a", Verdict.SKIP_REAL_API))
            continue

        prod_path = prod_dir / name
        if not prod_path.exists():
            summary.append(f"{name}: MISSING produced file")
            rows.append((name, "(file)", "exists", "<missing>", "exact", Verdict.MISSING))
            any_mismatch = True
            continue

        with ref_path.open("r", encoding="utf-8") as f:
            ref = json.load(f)
        with prod_path.open("r", encoding="utf-8") as f:
            prod = json.load(f)

        m, d = compare_node(ref, prod, "", tol, rows, name)
        if m:
            summary.append(f"{name}: STRUCTURAL MISMATCH")
        elif d:
            summary.append(f"{name}: numeric drift (within informational tolerance)")
        else:
            summary.append(f"{name}: ok")
        any_mismatch = any_mismatch or m
        any_drift = any_drift or d

    Path(args.report).parent.mkdir(parents=True, exist_ok=True)
    Path(args.report).write_text(render_report(rows), encoding="utf-8")

    print()
    print("=" * 60)
    print("Reproduction diff summary")
    print("=" * 60)
    for line in summary:
        print(line)
    print()
    print(f"Detailed report: {args.report}")

    if any_mismatch:
        print("VERDICT: STRUCTURAL MISMATCH (exit 1)")
        return 1
    if any_drift and args.strict_numeric:
        print("VERDICT: numeric drift, --strict-numeric set (exit 2)")
        return 2
    if any_drift:
        print("VERDICT: numeric drift within informational tolerance (exit 0)")
    else:
        print("VERDICT: clean (exit 0)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
